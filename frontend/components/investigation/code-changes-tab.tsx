"use client";

import { Check, FilePlus2, FlaskConical, GitCompare, X } from "lucide-react";
import { useMemo, useState } from "react";
import { DiffViewer } from "@/components/investigation/diff-viewer";
import { Alert } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardBody, CardHeader, CardTitle } from "@/components/ui/card";
import { CodeBlock } from "@/components/ui/code-block";
import { CopyButton } from "@/components/ui/copy-button";
import { DownloadButton } from "@/components/ui/download-button";
import { effectiveFiles, parseUnifiedDiff, patchForSelection, type DiffFile } from "@/lib/diff";
import { cn } from "@/lib/utils";
import type { FileChange, RepairResult } from "@/types/api";

type View = "diff" | "original" | "patched";
export type Decision = "accepted" | "rejected";
export type Decisions = Record<string, Decision>;

export type SkippedParts = Record<string, number[]>;

interface ReviewProps {
  decisions: Decisions;
  onDecide: (path: string, decision: Decision | null) => void;
  onDecideAll: (decision: Decision) => void;
  /** Blocks inside a file that the visitor chose to leave out of the patch, by file path. */
  skipped: SkippedParts;
  onToggleHunk: (path: string, index: number) => void;
}

export function CodeChangesTab({ result, decisions, onDecide, onDecideAll, skipped, onToggleHunk }: { result: RepairResult } & ReviewProps) {
  const files = useMemo(() => parseUnifiedDiff(result.diff), [result.diff]);
  const accepted = useMemo(() => new Set(result.changes.filter((c) => decisions[c.path] === "accepted").map((c) => c.path)), [result.changes, decisions]);
  const acceptedDiff = useMemo(() => patchForSelection(files, accepted, skipped), [files, accepted, skipped]);
  const included = useMemo(() => effectiveFiles(files, accepted, skipped).length, [files, accepted, skipped]);
  const skippedParts = Object.entries(skipped).reduce((n, [path, list]) => n + (accepted.has(path) ? list.length : 0), 0);
  const rejected = result.changes.filter((c) => decisions[c.path] === "rejected").length;
  const pending = result.changes.length - accepted.size - rejected;

  if (!result.diff || result.changes.length === 0) {
    return (
      <Alert tone="neutral" title="No patch was generated">
        {result.outcome === "insufficient_evidence"
          ? "A patch is only generated when the diagnosis is backed by code that exists in the repository."
          : "Every patch attempt was rejected by validation, or the AI could not produce a safe change. See the Overview tab for details."}
      </Alert>
    );
  }

  return (
    <div className="space-y-4">
      <Alert tone="info" title="Review before applying">
        This is a proposal generated by an AI model. RepoPilot never changes your repository: accept the files you want, then download
        only those and apply them yourself with <code className="font-mono">git apply repopilot.patch</code>.
      </Alert>

      <Card>
        <CardBody className="space-y-3">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <p className="text-sm" aria-live="polite">
              <strong>{accepted.size}</strong> accepted · <strong>{rejected}</strong> rejected · <strong>{pending}</strong> to review
              {skippedParts > 0 ? <> · <strong>{skippedParts}</strong> {skippedParts === 1 ? "part" : "parts"} left out</> : null}
            </p>
            <div className="flex flex-wrap gap-2">
              <Button variant="outline" size="sm" onClick={() => onDecideAll("accepted")}>
                <Check className="h-3.5 w-3.5" aria-hidden /> Accept all
              </Button>
              <Button variant="outline" size="sm" onClick={() => onDecideAll("rejected")}>
                <X className="h-3.5 w-3.5" aria-hidden /> Reject all
              </Button>
            </div>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <DownloadButton text={acceptedDiff} filename="repopilot.patch" mime="text/x-diff" label="Download accepted .patch" disabled={included === 0} />
            <CopyButton text={acceptedDiff} label="Copy accepted diff" className="border border-border" disabled={included === 0} />
            {included === 0 ? <span className="text-xs text-faint">Accept at least one file to download a patch.</span> : null}
          </div>
        </CardBody>
      </Card>

      {result.changes.map((change) => (
        <FileChangeCard
          key={change.path}
          change={change}
          diff={files.find((f) => f.path === change.path)}
          decision={decisions[change.path] ?? null}
          onDecide={(d) => onDecide(change.path, d)}
          skipped={skipped[change.path] ?? []}
          onToggleHunk={(index) => onToggleHunk(change.path, index)}
        />
      ))}

      {result.regression_test ? (
        <Card>
          <CardHeader>
            <CardTitle className="inline-flex items-center gap-2">
              <FlaskConical className="h-4 w-4 text-accent" aria-hidden /> Suggested regression test
            </CardTitle>
            <div className="flex items-center gap-2">
              <Badge tone={result.regression_test.executed ? "success" : "neutral"}>
                {result.regression_test.executed ? "Executed in sandbox" : "Not executed"}
              </Badge>
              <CopyButton text={result.regression_test.content} />
            </div>
          </CardHeader>
          <CardBody className="space-y-3">
            <p className="break-all font-mono text-[13px]">
              <FilePlus2 className="mr-1.5 inline h-3.5 w-3.5 text-faint" aria-hidden />
              {result.regression_test.path} <span className="text-faint">(new file)</span>
            </p>
            {result.regression_test.description ? <p className="text-sm text-muted">{result.regression_test.description}</p> : null}
            <CodeBlock code={result.regression_test.content} maxHeight="18rem" label="Regression test" />
          </CardBody>
        </Card>
      ) : null}
    </div>
  );
}

function FileChangeCard({
  change,
  diff,
  decision,
  onDecide,
  skipped,
  onToggleHunk,
}: {
  change: FileChange;
  diff?: DiffFile;
  decision: Decision | null;
  onDecide: (decision: Decision | null) => void;
  skipped: number[];
  onToggleHunk: (index: number) => void;
}) {
  const [view, setView] = useState<View>("diff");
  const views: { id: View; label: string; available: boolean }[] = [
    { id: "diff", label: "Diff", available: Boolean(diff) },
    { id: "original", label: "Original file", available: change.original_content != null },
    { id: "patched", label: "Patched file", available: change.patched_content != null },
  ];

  return (
    <Card className={cn(decision === "accepted" && "border-success/40", decision === "rejected" && "opacity-75")}>
      <CardHeader className="flex-wrap">
        <p className="min-w-0 break-all font-mono text-[13px]">
          <GitCompare className="mr-1.5 inline h-3.5 w-3.5 text-accent" aria-hidden />
          {change.path}
        </p>
        <div className="flex flex-wrap items-center gap-3">
          <span className="font-mono text-xs">
            <span className="text-success">+{change.additions}</span> <span className="text-danger">−{change.deletions}</span>
          </span>
          <div role="group" aria-label={`Decision for ${change.path}`} className="inline-flex gap-1.5">
            <Button
              variant={decision === "accepted" ? "primary" : "outline"}
              size="sm"
              aria-pressed={decision === "accepted"}
              onClick={() => onDecide(decision === "accepted" ? null : "accepted")}
            >
              <Check className="h-3.5 w-3.5" aria-hidden /> {decision === "accepted" ? "Accepted" : "Accept"}
            </Button>
            <Button
              variant={decision === "rejected" ? "danger" : "outline"}
              size="sm"
              aria-pressed={decision === "rejected"}
              onClick={() => onDecide(decision === "rejected" ? null : "rejected")}
            >
              <X className="h-3.5 w-3.5" aria-hidden /> {decision === "rejected" ? "Rejected" : "Reject"}
            </Button>
          </div>
        </div>
      </CardHeader>
      <CardBody className="space-y-3">
        <p className="text-sm leading-6 text-muted">{change.explanation}</p>

        <div className="flex flex-wrap items-center justify-between gap-2">
          <div role="group" aria-label={`View options for ${change.path}`} className="inline-flex rounded-lg border border-border bg-bg p-0.5">
            {views
              .filter((v) => v.available)
              .map((v) => (
                <button
                  key={v.id}
                  type="button"
                  aria-pressed={view === v.id}
                  onClick={() => setView(v.id)}
                  className={cn(
                    "cursor-pointer rounded-md px-3 py-1 text-xs font-medium transition-colors",
                    view === v.id ? "bg-surface-2 text-fg" : "text-muted hover:text-fg",
                  )}
                >
                  {v.label}
                </button>
              ))}
          </div>
          {view === "patched" && change.patched_content ? <CopyButton text={change.patched_content} label="Copy patched file" /> : null}
          {view === "original" && change.original_content ? <CopyButton text={change.original_content} label="Copy original" /> : null}
        </div>

        {view === "diff" && diff ? (
          <>
            {decision === "accepted" && diff.hunks.length > 1 ? (
              <p className="text-xs text-muted">
                This file has {diff.hunks.length} separate parts. Use “Leave this part out” on any part you don&apos;t want in the patch.
              </p>
            ) : null}
            <DiffViewer
              file={diff}
              review={decision === "accepted" && diff.hunks.length > 1 ? { skipped: new Set(skipped), onToggle: onToggleHunk } : undefined}
            />
          </>
        ) : null}
        {view === "original" && change.original_content != null ? (
          <CodeBlock code={change.original_content} highlight={diff?.removedOldLines} tone="del" label={`Original ${change.path}`} />
        ) : null}
        {view === "patched" && change.patched_content != null ? (
          <CodeBlock code={change.patched_content} highlight={diff?.addedNewLines} tone="add" label={`Patched ${change.path}`} />
        ) : null}
      </CardBody>
    </Card>
  );
}
