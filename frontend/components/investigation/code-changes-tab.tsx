"use client";

import { Download, FilePlus2, FlaskConical, GitCompare } from "lucide-react";
import { useMemo, useState } from "react";
import { DiffViewer } from "@/components/investigation/diff-viewer";
import { Alert } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { buttonVariants } from "@/components/ui/button";
import { Card, CardBody, CardHeader, CardTitle } from "@/components/ui/card";
import { CodeBlock } from "@/components/ui/code-block";
import { CopyButton } from "@/components/ui/copy-button";
import { api } from "@/lib/api";
import { parseUnifiedDiff, type DiffFile } from "@/lib/diff";
import { cn } from "@/lib/utils";
import type { FileChange, RepairResult } from "@/types/api";

type View = "diff" | "original" | "patched";

export function CodeChangesTab({ result, investigationId }: { result: RepairResult; investigationId: string }) {
  const files = useMemo(() => parseUnifiedDiff(result.diff), [result.diff]);

  if (!result.diff || result.changes.length === 0) {
    return (
      <Alert tone="neutral" title="No patch was generated">
        {result.outcome === "insufficient_evidence"
          ? "A patch is only generated when the diagnosis is backed by code that exists in the repository."
          : "Every patch attempt was rejected by validation, or the AI could not produce a safe change. See the Overview tab for details."}
      </Alert>
    );
  }

  let downloadHref: string | null = null;
  try {
    downloadHref = api.diffUrl(investigationId);
  } catch {
    downloadHref = null;
  }

  return (
    <div className="space-y-4">
      <Alert tone="info" title="Review before applying">
        This is a proposal generated by an AI model. Apply it with <code className="font-mono">git apply repopilot.patch</code> only after
        reading it.
      </Alert>

      <div className="flex flex-wrap items-center gap-2">
        <CopyButton text={result.diff} label="Copy full diff" className="border border-border" />
        {downloadHref ? (
          <a href={downloadHref} download className={cn(buttonVariants({ variant: "outline", size: "sm" }))}>
            <Download className="h-3.5 w-3.5" aria-hidden /> Download .patch
          </a>
        ) : null}
      </div>

      {result.changes.map((change) => (
        <FileChangeCard key={change.path} change={change} diff={files.find((f) => f.path === change.path)} />
      ))}

      {result.regression_test ? (
        <Card>
          <CardHeader>
            <CardTitle className="inline-flex items-center gap-2">
              <FlaskConical className="h-4 w-4 text-accent" aria-hidden /> Suggested regression test
            </CardTitle>
            <div className="flex items-center gap-2">
              <Badge tone={result.regression_test.executed ? "success" : "neutral"}>
                {result.regression_test.executed ? "Executed in sandbox" : "Not executed"}
              </Badge>
              <CopyButton text={result.regression_test.content} />
            </div>
          </CardHeader>
          <CardBody className="space-y-3">
            <p className="break-all font-mono text-[13px]">
              <FilePlus2 className="mr-1.5 inline h-3.5 w-3.5 text-faint" aria-hidden />
              {result.regression_test.path} <span className="text-faint">(new file)</span>
            </p>
            {result.regression_test.description ? <p className="text-sm text-muted">{result.regression_test.description}</p> : null}
            <CodeBlock code={result.regression_test.content} maxHeight="18rem" label="Regression test" />
          </CardBody>
        </Card>
      ) : null}
    </div>
  );
}

function FileChangeCard({ change, diff }: { change: FileChange; diff?: DiffFile }) {
  const [view, setView] = useState<View>("diff");
  const views: { id: View; label: string; available: boolean }[] = [
    { id: "diff", label: "Diff", available: Boolean(diff) },
    { id: "original", label: "Original file", available: change.original_content != null },
    { id: "patched", label: "Patched file", available: change.patched_content != null },
  ];

  return (
    <Card>
      <CardHeader className="flex-wrap">
        <p className="min-w-0 break-all font-mono text-[13px]">
          <GitCompare className="mr-1.5 inline h-3.5 w-3.5 text-accent" aria-hidden />
          {change.path}
        </p>
        <span className="font-mono text-xs">
          <span className="text-success">+{change.additions}</span> <span className="text-danger">−{change.deletions}</span>
        </span>
      </CardHeader>
      <CardBody className="space-y-3">
        <p className="text-sm leading-6 text-muted">{change.explanation}</p>

        <div className="flex flex-wrap items-center justify-between gap-2">
          <div role="group" aria-label={`View options for ${change.path}`} className="inline-flex rounded-lg border border-border bg-bg p-0.5">
            {views
              .filter((v) => v.available)
              .map((v) => (
                <button
                  key={v.id}
                  type="button"
                  aria-pressed={view === v.id}
                  onClick={() => setView(v.id)}
                  className={cn(
                    "cursor-pointer rounded-md px-3 py-1 text-xs font-medium transition-colors",
                    view === v.id ? "bg-surface-2 text-fg" : "text-muted hover:text-fg",
                  )}
                >
                  {v.label}
                </button>
              ))}
          </div>
          {view === "patched" && change.patched_content ? <CopyButton text={change.patched_content} label="Copy patched file" /> : null}
          {view === "original" && change.original_content ? <CopyButton text={change.original_content} label="Copy original" /> : null}
        </div>

        {view === "diff" && diff ? <DiffViewer file={diff} /> : null}
        {view === "original" && change.original_content != null ? (
          <CodeBlock code={change.original_content} highlight={diff?.removedOldLines} tone="del" label={`Original ${change.path}`} />
        ) : null}
        {view === "patched" && change.patched_content != null ? (
          <CodeBlock code={change.patched_content} highlight={diff?.addedNewLines} tone="add" label={`Patched ${change.path}`} />
        ) : null}
      </CardBody>
    </Card>
  );
}
