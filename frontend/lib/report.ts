import { verdictFor } from "@/lib/verdict";
import type { Investigation } from "@/types/api";

/** A fence long enough that the text inside can never close it. */
function fence(text: string, lang = ""): string {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((m) => m.length));
  const ticks = "`".repeat(longest + 1);
  return `${ticks}${lang}\n${text.replace(/\n$/, "")}\n${ticks}`;
}

const quote = (text: string) => text.split("\n").map((l) => `> ${l}`).join("\n");

/**
 * A plain Markdown report of one investigation, built only from what the backend returned. It states what was and was
 * not verified exactly as the screen does, so a shared report cannot claim more than the app did.
 */
export function buildReport(inv: Investigation): string {
  const r = inv.result;
  const repo = inv.repository;
  if (!r) return "";
  const verdict = verdictFor(r);
  const name = repo ? `${repo.owner}/${repo.name}` : inv.repository_url.replace("https://github.com/", "");
  const out: string[] = [];
  const add = (...lines: string[]) => out.push(...lines, "");

  add(`# RepoPilot AI report: ${name}`);
  add(
    `- **Repository:** ${inv.repository_url}${repo?.commit_sha ? ` (commit \`${repo.commit_sha.slice(0, 8)}\`)` : ""}`,
    `- **Investigated:** ${inv.updated_at}`,
    ...(repo?.primary_language ? [`- **Language:** ${repo.primary_language}${repo.frameworks?.length ? `, ${repo.frameworks.slice(0, 6).join(", ")}` : ""}`] : []),
    `- **Result:** ${verdict.headline}`,
    `- **Confidence:** ${r.confidence}`,
    `- **Model:** ${r.llm_model || "unknown"}`,
  );
  add("> This report was generated by an AI system. Review every claim and every change before relying on it.");

  add("## Bug report", quote(inv.bug_description));
  if (inv.stack_trace) add("### Stack trace", fence(inv.stack_trace));

  add("## Root cause", r.root_cause || "No root cause was established.");
  const verified = r.evidence.filter((e) => e.verified).length;
  if (r.evidence.length > 0) {
    add(`## Evidence (${verified} of ${r.evidence.length} quotes verified in the repository)`);
    for (const e of r.evidence) {
      add(`### \`${e.file}:${e.start_line}${e.end_line > e.start_line ? `-${e.end_line}` : ""}\` ${e.verified ? "(verified)" : "(NOT verified: this code was not found in the file)"}`, e.explanation);
      if (e.verified && e.snippet) add(fence(e.snippet));
    }
  }

  if (r.research?.status === "completed") {
    add(`## Web research (${r.research.sources.length} sources found on the internet)`);
    if (r.research.summary) add(r.research.summary);
    add("Web sources are background context. Only code quoted from the repository counts as evidence.");
    for (const s of r.research.sources) {
      add(`- [${s.title}](${s.url}) (${s.kind === "official" ? "official documentation" : s.kind}, ${s.domain})${s.used ? ` — compared with the code: ${s.relevance}` : ""}`);
    }
    out.push("");
  } else {
    add("## Web research", `Not used for this investigation${r.research?.note ? `: ${r.research.note}` : "."}`);
  }

  if (r.changes.length > 0) {
    const adds = r.changes.reduce((n, c) => n + c.additions, 0);
    const dels = r.changes.reduce((n, c) => n + c.deletions, 0);
    add(`## Proposed change (${r.changes.length} file${r.changes.length === 1 ? "" : "s"}, +${adds} −${dels})`);
    for (const c of r.changes) add(`- \`${c.path}\`: ${c.explanation}`);
    out.push("");
    add("Apply it to your own copy with `git apply repopilot.patch` after reviewing it.", fence(r.diff, "diff"));
    if (r.regression_test) add(`### Suggested regression test: \`${r.regression_test.path}\``, r.regression_test.description, fence(r.regression_test.content));
  } else {
    add("## Proposed change", "No patch was generated.");
  }

  add("## Validation", `**${r.validation.status.replace("_", " ")}**: ${r.validation.summary}`);
  if (r.validation.detected_commands?.length) {
    add(`Detected test ${r.validation.detected_commands.length === 1 ? "command" : "commands"}${r.validation.runs.length === 0 ? " (not run by RepoPilot)" : ""}:`, fence(r.validation.detected_commands.join("\n"), "sh"));
  }

  if (r.risks.length) add("## Remaining risks", r.risks.map((x) => `- ${x}`).join("\n"));
  if (r.limitations.length) add("## Limitations", r.limitations.map((x) => `- ${x}`).join("\n"));

  const issues = repo?.quality ?? [];
  if (issues.length) {
    add("## Code health observations", "Quick automatic checks, not a full audit.");
    add(issues.map((q) => `- **${q.severity === "warning" ? "Warning" : "Note"}: ${q.title}**${q.path ? ` (\`${q.path}${q.line ? `:${q.line}` : ""}\`)` : ""}. ${q.detail}`).join("\n"));
  }
  const folders = repo?.structure ?? [];
  if (folders.length) {
    add("## Project structure", folders.map((f) => `- \`${f.path === "(root)" ? "(top level)" : `${f.path}/`}\`: ${f.role}, ${f.files} file${f.files === 1 ? "" : "s"}${f.languages.length ? `, ${f.languages.join(", ")}` : ""}`).join("\n"));
  }

  add("---", "Generated by RepoPilot AI. https://github.com/Xdiad47/RepoPilot-AI");
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

export function reportFilename(inv: Investigation): string {
  const slug = (inv.repository ? `${inv.repository.owner}-${inv.repository.name}` : "investigation").toLowerCase().replace(/[^a-z0-9._-]+/g, "-");
  return `repopilot-report-${slug}.md`;
}
